function metadataForPath(path: string): { changefreq: string; priority: string } {
  if (path === "/") return { changefreq: "daily", priority: "1.0" };
  if (path === "/blog/" || path === "/recipes/") return { changefreq: "weekly", priority: "0.9" };
  if (path.startsWith("/calculators/")) return { changefreq: "monthly", priority: "0.8" };
  if (path.startsWith("/blog/") || path.startsWith("/recipes/")) return { changefreq: "monthly", priority: "0.7" };
  if (path === "/privacy-policy/" || path === "/terms-of-use/") return { changefreq: "yearly", priority: "0.3" };
  return { changefreq: "monthly", priority: "0.5" };
}

function renderUrl(path: string): string {
  const { changefreq, priority } = metadataForPath(path);
  return `  <url><loc>${BASE_URL}${path}</loc><lastmod>${LASTMOD}</lastmod><changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`;
}

export function renderUrlSet(paths: readonly string[]): string {
  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
    ...paths.map(renderUrl),
    `</urlset>`,
  ].join("\n");
}

export function sitemapResponse(paths: readonly string[]): Response {
  return new Response(renderUrlSet(paths), {
    headers: {
      "Content-Type": "application/xml; charset=utf-8",
      "Cache-Control": "public, max-age=3600",
      "X-Content-Type-Options": "nosniff",
    },
  });
}
